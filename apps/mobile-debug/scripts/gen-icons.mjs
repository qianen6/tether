// Turns assets/herdr/{ui,icons}/*.svg into src/icons.generated.ts (XML strings for
// react-native-svg's SvgXml). Program icons the Herdr app tints (TINTED) get every
// colour replaced by currentColor, as its tint does; the others keep their colours.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../assets/herdr");
const TINTED = new Set(["gemini", "opencode", "cursor", "copilot", "shell", "agent", "program"]);

const load = (dir, tint) =>
  Object.fromEntries(
    readdirSync(join(root, dir))
      .filter(f => f.endsWith(".svg"))
      .map(f => {
        const name = basename(f, ".svg");
        let xml = readFileSync(join(root, dir, f), "utf8").replace(/<title>.*?<\/title>/g, "").replace(/\s+/g, " ").trim();
        // react-native-svg ignores CSS `style` and needs sizes it can scale.
        xml = xml.replace(/ style="[^"]*"/g, "").replace(/ (width|height)="1em"/g, "");
        if (tint(name)) xml = xml.replace(/(fill|stroke)="(?!none|currentColor)[^"]*"/g, '$1="currentColor"');
        return [name, xml];
      }),
  );

const ui = load("ui", () => false);
const programs = load("icons", n => TINTED.has(n));
writeFileSync(
  join(here, "../src/icons.generated.ts"),
  `// Generated by scripts/gen-icons.mjs from assets/herdr; do not edit.\n` +
    `export const UI_ICONS = ${JSON.stringify(ui, null, 1)} as const;\n` +
    `export const PROGRAM_ICONS: Record<string, string> = ${JSON.stringify(programs, null, 1)};\n`,
);
console.log("icons:", Object.keys(ui).length, "ui,", Object.keys(programs).length, "programs");

// Inlines xterm.js into the terminal WebView page, so the phone never fetches
// it from a CDN. Runs on postinstall; writes src/terminal/page.generated.ts.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(join(here, "../package.json"));
const read = spec => readFileSync(require.resolve(spec), "utf8");
const xterm = read("@xterm/xterm/lib/xterm.js");
const fit = read("@xterm/addon-fit/lib/addon-fit.js");
const webgl = read("@xterm/addon-webgl/lib/addon-webgl.js");
const graphemes = read("@xterm/addon-unicode-graphemes/lib/addon-unicode-graphemes.js");
const css = read("@xterm/xterm/css/xterm.css");
const boot = readFileSync(join(here, "terminal-boot.js"), "utf8");
// The phone's own monospace fonts lack box drawing at one width: TUIs like Codex's come out
// ragged; and Android draws ⏺ ✔ ⚠ from its colour emoji font. JetBrains Mono and Herdr
// Anywhere's cuts of Noto Sans Symbols (OFL, assets/herdr/fonts) go in with the page.
const font = (family, file) =>
  `@font-face{font-family:'${family}';src:url(data:font/woff;base64,${readFileSync(join(here, "../assets/herdr/fonts", file)).toString("base64")}) format('woff')${family === "JetBrains Mono" ? ";font-weight:100 800" : ""}}`;
const fonts = [
  font("JetBrains Mono", "JetBrainsMono-Variable.woff"),
  font("Noto Sans Symbols 2", "NotoSansSymbols2-Subset.woff"),
  font("Noto Sans Symbols", "NotoSansSymbols-Subset.woff"),
  font("Noto Sans Mono", "NotoSansMono-Subset.woff"),
].join("\n");

// The page's look (Herdr's terminal: JetBrains Mono at medium weight, cells 1.15 times
// the font's height; no padding at the sides on a phone). The app replaces __THEME__ with
// xterm's theme object before loading the page. Messages: scripts/terminal-boot.js.
const PAD = 8;
const config = `{"theme":__THEME__,"fonts":"'JetBrains Mono', 'Noto Sans Symbols 2', 'Noto Sans Symbols', 'Noto Sans Mono', monospace","fontSize":12.5,"fontWeight":500,"fontWeightBold":700,"lineHeight":1.15,"scrollback":5000,"pad":${PAD}}`;
const page = `<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">
<style>${fonts}
${css}
html,body{margin:0;height:100%;overflow:hidden;touch-action:none;-webkit-user-select:none;user-select:none}#t{position:absolute;inset:${PAD}px 0}</style>
</head><body><div id="t"></div>
<script>${xterm}</script><script>${fit}</script><script>${webgl}</script><script>${graphemes}</script>
<script>window.__terminal=${config};document.body.style.background=window.__terminal.theme.background;</script>
<script>${boot}</script></body></html>`;

writeFileSync(
  join(here, "../src/terminal/page.generated.ts"),
  `// Generated by scripts/build-terminal.mjs from @xterm/xterm; do not edit.\nexport const TERMINAL_HTML: string = ${JSON.stringify(page)};\n`,
);
console.log("terminal page:", Math.round(page.length / 1024), "KiB");
